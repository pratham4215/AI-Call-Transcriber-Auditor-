"""
crm_excel.py — CRM data loader from Excel export.

Reads data/audit data.xlsx (or CRM_EXCEL_PATH env var), indexes rows by
Customer Mobile, and returns crm_details dicts compatible with the pipeline's
normalized schema.

Usage:
    from core.audit.crm_excel import get_crm_by_stem, get_crm_by_phone
    details = get_crm_by_stem("9000000001 - BOD")   # extracts phone from stem
    details = get_crm_by_phone("9000000001")
    reload()                                          # force re-read from disk
"""
from __future__ import annotations

import os
import re
import threading
from datetime import date, datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

try:
    import openpyxl  # type: ignore
except ImportError:
    openpyxl = None  # type: ignore

from .utils import mask_phone

# ── Config ────────────────────────────────────────────────────────────────────

_DEFAULT_EXCEL = Path(__file__).resolve().parents[2] / "data" / "audit data.xlsx"
CRM_EXCEL_PATH = Path(os.environ.get("CRM_EXCEL_PATH", str(_DEFAULT_EXCEL)))

# Primary Disposition → audit call type
_DISP_TO_TYPE: Dict[str, str] = {
    "BOOKED":     "BOOKING",
    "ESCALATION": "ESCALATION",
    "SNR":        "SERVICE_NT_REQUIRED",
    "FOLLOW_UP":  "FOLLOW_UPS",
    "CALLBACK":   "FOLLOW_UPS",
}

_NSD_TRIGGER: Dict[str, str] = {
    "TENURE":  "calendar-based (tenure)",
    "MILEAGE": "odometer-based (mileage)",
}

# ── Helpers ───────────────────────────────────────────────────────────────────

def _s(v: Any) -> Optional[str]:
    if v is None:
        return None
    s = str(v).strip()
    return s or None


def _dt(v: Any) -> Optional[str]:
    if isinstance(v, (datetime, date)):
        return v.strftime("%Y-%m-%d")
    s = _s(v)
    return s


def _phone_digits(v: Any) -> Optional[str]:
    if v is None:
        return None
    m = re.search(r"[6-9]\d{9}", str(v))
    return m.group() if m else _s(v)


def _infer_call_type(row: Dict[str, Any]) -> Optional[str]:
    disp  = (_s(row.get("Primary Disposition")) or "").upper()
    form  = (_s(row.get("Disposition Form Type")) or "").upper()
    snr   = _s(row.get("SNR Main Reason"))
    fu    = row.get("Follow Up Date") or row.get("Follow Up Reason")

    if snr or "SNR" in form:
        return "SERVICE_NT_REQUIRED"
    ct = _DISP_TO_TYPE.get(disp)
    if ct:
        return ct
    if fu:
        return "FOLLOW_UPS"
    return None


# ── Row → crm_details ─────────────────────────────────────────────────────────

def _row_to_crm(row: Dict[str, Any]) -> Dict[str, Any]:
    nsd_type    = _s(row.get("NSD Due Type"))        # FR2, PMS2, PMS3 …
    nsd_trigger = _s(row.get("NSD Generated By"))    # TENURE / MILEAGE
    pickup      = _s(row.get("Pick Up Option"))

    # NSD context sentence for LLM prompt
    nsd_parts: List[str] = []
    if nsd_trigger:
        nsd_parts.append(_NSD_TRIGGER.get(nsd_trigger.upper(), nsd_trigger))
    if nsd_type:
        nsd_parts.append(f"service type {nsd_type}")
    if row.get("NSD Due Date"):
        nsd_parts.append(f"due {_dt(row.get('NSD Due Date'))}")
    nsd_context = "; ".join(nsd_parts) or None

    # Service history from SNR last-service fields
    service_history: List[Dict[str, Any]] = []
    last_svc_date = _dt(row.get("SNR Last Service Date"))
    if last_svc_date:
        service_history.append({
            "service_date": last_svc_date,
            "workshop": _s(row.get("SNR Last Service Workshop"))
                        or _s(row.get("Authorized Dealer Name"))
                        or _s(row.get("Unauthorized Workshop Name")),
            "service_type": _s(row.get("SNR Workshop Type")),
            "odometer_km": None,
        })

    # Disposition
    disposition: Dict[str, Any] = {
        "status":                 _s(row.get("Primary Disposition")),
        "form_type":              _s(row.get("Disposition Form Type")),
        "snr_main_reason":        _s(row.get("SNR Main Reason")),
        "snr_distance_sub_reason":_s(row.get("SNR Distance Sub Reason")),
        "snr_workshop_type":      _s(row.get("SNR Workshop Type")),
        "authorized_dealer":      _s(row.get("Authorized Dealer Name")),
        "unauthorized_workshop":  _s(row.get("Unauthorized Workshop Name")),
    }

    # Booking
    booking: Optional[Dict[str, Any]] = None
    if row.get("Booking Date Time") or row.get("Booked Service Type"):
        booking = {
            "booking_date_time": _dt(row.get("Booking Date Time")),
            "service_type":      _s(row.get("Booked Service Type")),
            "workshop":          _s(row.get("Booking Workshop Location")),
            "time_start":        _s(row.get("Booking Time Start")),
            "time_end":          _s(row.get("Booking Time End")),
            "status":            _s(row.get("Booked Status")),      # NO_SHOW / CONFIRMED
        }

    # Follow-up
    follow_up: Optional[Dict[str, Any]] = None
    if row.get("Follow Up Date") or row.get("Follow Up Reason"):
        follow_up = {
            "date":   _dt(row.get("Follow Up Date")),
            "reason": _s(row.get("Follow Up Reason")),
        }

    crm: Dict[str, Any] = {
        "schema_version": "crm-excel-v1",
        "cre": {
            "name":        _s(row.get("CRE ID")),        # CRE ID col = full name
            "employee_id": _s(row.get("CRE Name")),      # CRE Name col = code
        },
        "customer": {
            "name":  _s(row.get("Customer Name")),
            # phone stored masked — raw digit key used only for lookup
            "phone": mask_phone(_s(row.get("Customer Mobile")) or ""),
        },
        "vehicle": {
            "model":               _s(row.get("Model")),
            "model_category":      _s(row.get("Model Category")),
            "registration_number": _s(row.get("Registration Number")),
            "vin_number":          _s(row.get("VIN Number")),
            "engine_number":       _s(row.get("Engine Number")),
            "chassis_number":      _s(row.get("Chassis Number")),
            "service_due_date":    _dt(row.get("NSD Due Date")),
            "next_service_type":   nsd_type,
            "nsd_trigger":         nsd_trigger,
            "nsd_context":         nsd_context,
        },
        "service_profile": {
            "campaign":          _s(row.get("Call Campaign")),
            "campaign_tagging":  _s(row.get("Campaign Tagging")),
            "workshop":          _s(row.get("Workshop Name")),
            "pickup_drop_status": pickup,
            "dms_verified":      _s(row.get("Is Verified With DMS")),
        },
        "call_meta": {
            "call_date":      _dt(row.get("Call Date")),
            "call_duration":  _s(row.get("Call Duration")),
            "submitted_date": _dt(row.get("Submitted Date")),
        },
        "remarks": {
            "cre_remark":      mask_phone(_s(row.get("CRE Remark")) or ""),
            "customer_remark": mask_phone(_s(row.get("Customer Remark")) or ""),
        },
        "disposition":       disposition,
        "service_history":   service_history,
    }

    if booking:
        crm["booking"] = booking
    if follow_up:
        crm["follow_up"] = follow_up

    call_type = _infer_call_type(row)
    if call_type:
        crm["audit_call_type"] = call_type

    return crm


# ── Cache & public API ────────────────────────────────────────────────────────

_CACHE: Optional[Dict[str, Dict[str, Any]]] = None   # phone (10 digits) → crm
_CACHE_LOCK = threading.RLock()


def _load() -> Dict[str, Dict[str, Any]]:
    global _CACHE
    if _CACHE is not None:
        return _CACHE

    if openpyxl is None or not CRM_EXCEL_PATH.exists():
        _CACHE = {}
        return _CACHE

    wb = openpyxl.load_workbook(str(CRM_EXCEL_PATH), read_only=True, data_only=True)
    ws = wb.active
    raw_rows = list(ws.iter_rows(values_only=True))
    wb.close()
    if not raw_rows:
        _CACHE = {}
        return _CACHE

    headers = [str(h).strip() if h is not None else f"_col{i}"
               for i, h in enumerate(raw_rows[0])]
    index: Dict[str, Dict[str, Any]] = {}

    for raw in raw_rows[1:]:
        row = {headers[i]: v for i, v in enumerate(raw) if i < len(headers)}
        phone = _phone_digits(row.get("Customer Mobile"))
        if not phone:
            continue
        index[phone] = _row_to_crm(row)

    _CACHE = index
    return _CACHE


def reload() -> int:
    """Force re-read from disk. Returns number of rows loaded."""
    global _CACHE
    with _CACHE_LOCK:
        _CACHE = None
        return len(_load())


def get_crm_by_phone(phone: str) -> Optional[Dict[str, Any]]:
    """Look up CRM row by customer phone. Accepts any format — uses last 10 digits."""
    key = re.sub(r"\D", "", str(phone))[-10:]
    with _CACHE_LOCK:
        return _load().get(key)


def get_crm_by_stem(stem: str) -> Optional[Dict[str, Any]]:
    """
    Extract a 10-digit mobile number from an audio filename stem and return
    the matching CRM row, or None if no match.

    Handles stems like:
        '9000000001'
        '9000000001 - BOD'
        '9000000001-BOD'
        '91900000001-BMS'   (11-digit with country prefix)
    """
    m = re.search(r"[6-9]\d{9}", stem)
    if not m:
        return None
    return get_crm_by_phone(m.group())


def list_loaded() -> List[str]:
    """Return list of phone keys currently in cache (masked for display)."""
    with _CACHE_LOCK:
        return [mask_phone(k) for k in _load().keys()]
